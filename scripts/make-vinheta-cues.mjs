// Generates the SFX cue sheet for the BruteForceRaceCondition vinheta, derived from the same
// scene lengths the component uses — so the cues cannot silently drift out of sync with the
// animation when a scene is retimed.
//
//   node scripts/make-vinheta-cues.mjs
//
// Writes docs/vinheta-sfx-cues.md (human/DAW-readable) and temp/v3-sfx-events.txt (the
// --events string for `ve add-sfx`).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));

/** Read SCENE_SECONDS out of the component source. Node cannot import JSX, and the alternative
 *  (duplicating the numbers here) is exactly the drift this script exists to prevent —
 *  `remotion-render.mjs` reads its COMPONENTS list the same way. */
function readSceneSeconds() {
  const src = fs.readFileSync(
    path.join(ROOT, 'remotion', 'scenes', 'BruteForceRaceCondition.jsx'), 'utf8');
  const block = /export const SCENE_SECONDS = \{([\s\S]*?)\};/.exec(src);
  if (!block) throw new Error('SCENE_SECONDS not found in BruteForceRaceCondition.jsx');
  const out = {};
  for (const m of block[1].matchAll(/(\w+)\s*:\s*([\d.]+)/g)) out[m[1]] = parseFloat(m[2]);
  if (!Object.keys(out).length) throw new Error('SCENE_SECONDS parsed empty');
  return out;
}
const SCENE_SECONDS = readSceneSeconds();

const at = {};
{
  let acc = 0;
  for (const k of Object.keys(SCENE_SECONDS)) { at[k] = acc; acc += SCENE_SECONDS[k]; }
}

